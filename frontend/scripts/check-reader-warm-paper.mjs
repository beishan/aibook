import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { browser, setup, errors, capture, initialSettings } from './reader-ui-fixture.mjs'

const screenshotDir = process.env.READER_SCREENSHOT_DIR || '/tmp/reader-warm-paper-review'
await mkdir(screenshotDir, { recursive: true })
const paperSettings = { ...initialSettings, appearance: 'warmPaper' }
const selectText = async page => {
  await page.locator('.reader-text p').first().evaluate(element => {
    const range = document.createRange()
    range.selectNodeContents(element)
    const selection = window.getSelection()
    selection.removeAllRanges()
    selection.addRange(range)
    element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }))
  })
  await page.getByRole('toolbar', { name: '选中文字操作' }).waitFor()
}

try {
  const desktop = await setup(1536, paperSettings)
  const { page } = desktop
  const rail = page.getByRole('complementary', { name: '纸感阅读工具' })
  await rail.waitFor()
  assert.equal(await rail.locator('nav button').first().evaluate(el => getComputedStyle(el).display), 'flex')
  assert.equal(await page.locator('.side-panel').count(), 0)
  assert.equal(await page.locator('.blue-topbar').count(), 0)
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).fontSize), '24px')
  await capture(page, `${screenshotDir}/01-overview.png`)
  await rail.getByRole('button', { name: '目录', exact: true }).click()
  await page.locator('.warm-panel-heading').waitFor()
  await capture(page, `${screenshotDir}/02-contents.png`)
  await page.locator('.toc-item').nth(1).click()
  await page.waitForFunction(() => document.querySelector('.toc-item.active')?.textContent.includes('第二章'))
  await rail.getByRole('button', { name: '搜索', exact: true }).click()
  await page.locator('#reader-search-input').fill('境界')
  await page.locator('.search-result-item').first().waitFor()
  await page.locator('.search-result-item').first().click()
  assert.ok(await page.locator('.search-result-excerpt mark').count() > 0)
  await capture(page, `${screenshotDir}/03-search.png`)
  await rail.getByRole('button', { name: '书签', exact: true }).click()
  assert.equal(await page.locator('.warm-panel--right').count(), 1)
  await page.locator('.bookmark-add-btn').click()
  await page.waitForFunction(() => document.querySelectorAll('.bookmark-item').length === 2)
  await capture(page, `${screenshotDir}/04-bookmarks.png`)
  const tabs = page.getByRole('radiogroup', { name: '阅读侧栏' })
  await tabs.getByRole('radio', { name: '书签', exact: true }).focus()
  await page.keyboard.press('End')
  assert.equal(await tabs.getByRole('radio', { name: '划线', exact: true }).getAttribute('aria-checked'), 'true')
  await capture(page, `${screenshotDir}/05-highlights.png`)
  await tabs.getByRole('radio', { name: '笔记', exact: true }).click()
  await page.locator('.blue-highlight-quote').first().click()
  await page.getByRole('textbox', { name: '笔记内容' }).fill('温暖纸感主题中的阅读笔记')
  await capture(page, `${screenshotDir}/06-annotation.png`)
  await page.getByRole('button', { name: '保存笔记', exact: true }).click()
  await page.locator('.highlight-editor').waitFor({ state: 'hidden' })
  await rail.getByRole('button', { name: '划线', exact: true }).click()
  await selectText(page)
  await capture(page, `${screenshotDir}/07-selection.png`)
  await page.getByRole('button', { name: '划线颜色 #a9e8b3', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.highlight-item').length === 3)
  await rail.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '增大字号' }).waitFor()
  await capture(page, `${screenshotDir}/08-settings.png`)
  await page.locator('.blue-type-settings select').selectOption('SimHei, sans-serif')
  assert.ok(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).fontFamily.includes('SimHei')))
  await page.locator('.blue-type-settings select').selectOption('default')
  await page.getByRole('radiogroup', { name: '对齐方式' }).getByRole('radio', { name: '左对齐', exact: true }).click()
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).textAlign), 'left')
  await page.getByRole('button', { name: '增大字号' }).click()
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.reader-text p')).fontSize === '25px')
  await page.waitForResponse(response => response.url().includes('/api/user/preferences') && response.request().method() === 'PUT' && response.request().postDataJSON()?.readerSettings?.warmPaper?.fontSize === 25)
  assert.equal(desktop.getPreferences().readerSettings.fontSize, 16)
  await page.getByRole('button', { name: '墨夜黑', exact: true }).click()
  await capture(page, `${screenshotDir}/09-night.png`)
  assert.equal(await rail.locator('nav button').first().evaluate(el => getComputedStyle(el).color), 'rgb(189, 203, 169)')
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el, '::highlight(reader-highlight-1)').color), 'rgb(36, 40, 33)')
  await page.getByRole('button', { name: '宣纸白', exact: true }).click()
  const appearance = page.getByRole('radiogroup', { name: '正式阅读器界面样式' })
  await appearance.getByRole('radio', { name: '浅蓝灰', exact: true }).click()
  await page.locator('.blue-topbar').waitFor()
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).fontSize), '22px')
  await appearance.getByRole('radio', { name: '经典', exact: true }).click()
  await page.locator('.reader-view:not(.blue-gray-mode):not(.warm-paper-mode)').waitFor()
  assert.equal(await page.locator('.reader-body').evaluate(el => getComputedStyle(el).fontSize), '16px')
  await page.getByRole('radio', { name: '温暖纸感 草木与书香' }).click()
  await page.getByRole('button', { name: '增大字号' }).waitFor()
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).fontSize), '25px')
  await page.keyboard.press('Escape')
  await rail.getByRole('button', { name: '全屏', exact: true }).click()
  await page.locator('.fullscreen-mode').waitFor()
  assert.equal(await page.locator('.warm-tool-rail').count(), 0)
  await capture(page, `${screenshotDir}/10-fullscreen.png`)
  await page.getByRole('button', { name: '退出全屏', exact: true }).first().click()
  if (desktop.getPreferences().readerSettings.appearance !== 'warmPaper') {
    await page.waitForResponse(response => response.url().includes('/api/user/preferences') && response.request().postDataJSON()?.readerSettings?.appearance === 'warmPaper')
  }
  await page.reload()
  await rail.waitFor()
  assert.equal(await page.locator('.reader-text p').first().evaluate(el => getComputedStyle(el).fontSize), '25px')
  await desktop.context.close()
  for (const width of [320, 390, 768]) {
    const test = await setup(width, paperSettings)
    const tools = test.page.getByRole('complementary', { name: '纸感阅读工具' })
    await tools.getByRole('button', { name: '目录', exact: true }).click()
    await test.page.getByRole('button', { name: '关闭侧栏', exact: true }).click()
    await tools.getByRole('button', { name: '设置', exact: true }).click()
    await test.page.getByRole('button', { name: '增大字号' }).waitFor()
    await capture(test.page, `${screenshotDir}/mobile-${width}.png`)
    assert.equal(await test.page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await test.context.close()
  }
  for (const format of ['md', 'structured', 'html', 'epub', 'pdf']) {
    const test = await setup(1280, paperSettings, format)
    await test.page.locator('.warm-reader-header').waitFor()
    await capture(test.page, `${screenshotDir}/format-${format}.png`)
    await test.context.close()
  }
  assert.deepEqual(errors, [])
  console.log('Warm paper: panels, notes, selection, theme isolation, alignment, account persistence, fullscreen, mobile and six formats passed')
} finally {
  await browser.close()
}
